"""Derive the VH-15 data management list (DML) from the BOM and the BOM-to-SNS map.

Inputs (relative to the sample root):
  bom/VH15-0000_BOM.csv   SolidWorks-style indented BOM export
  sns/VH15-SNS.csv        project SNS (system, subsystem, sub-subsystem, assembly)
  sns/bom-sns-map.csv     maintenance decisions: SNS position, disassembly code, LRU flag, extra tasks

Outputs:
  dml/VH15-DML.md         every planned data module, with its DMC and title
  dml/coverage.md         consistency and coverage findings

Rules:
  - Each LRU gets a remove (520) and an install (720) procedure.
  - EXTRA TASKS adds information codes to a row (040 description, 941 IPD, 270 adjust, ...).
  - Bought parts with no row in the map are reported: nobody has decided whether they are
    replaceable. Standard fasteners (ISO part numbers) are exempt.

Usage: python tools/make_dml.py   (from the sample root)
"""

import csv
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
MI, SDC = "VH15", "A"

# The information codes this project uses. Their names come from the CSDB's .dmtypes file
# (written by `s1kd-defaults -i`), so they match the S1000D Issue 7 standard names.
PROJECT_CODES = ["00W", "022", "040", "042", "241", "270", "340", "520", "720", "941"]


def load_info_names():
    names = {}
    for line in (ROOT / "csdb/.dmtypes").read_text(encoding="utf-8").splitlines():
        parts = line.split(None, 2)
        if len(parts) == 3 and parts[0] in PROJECT_CODES:
            names[parts[0]] = parts[2]
    return names


INFO_NAMES = load_info_names()

# Whole-unit data modules: (information code, item location code)
GENERAL = [("022", "D"), ("00W", "D"), ("040", "A"), ("042", "A")]


def read(rel):
    with open(ROOT / rel, encoding="utf-8", newline="") as f:
        return list(csv.DictReader(f))


def tech_name(description):
    """'VALVE, PRESSURE RELIEF, 30-210 BAR' -> 'Pressure relief valve'."""
    parts = [p.strip() for p in description.split(",")]
    name = f"{parts[1]} {parts[0]}" if len(parts) > 1 and not parts[1][0].isdigit() else parts[0]
    name = name.replace("ASSY", "assembly").lower()
    return name[0].upper() + name[1:]


def dmc(sns, disassy, info, ilc):
    return f"DMC-{MI}-{SDC}-{sns}-{disassy}A-{info}A-{ilc}"


def main():
    bom = {r["PART NUMBER"]: r for r in read("bom/VH15-0000_BOM.csv")}
    sns_rows = read("sns/VH15-SNS.csv")
    sns_titles = {
        f"{r['SYSTEM']}-{r['SUBSYSTEM']}{r['SUBSUBSYSTEM']}-{r['ASSEMBLY']}": r["TITLE"]
        for r in sns_rows
    }
    mapping = read("sns/bom-sns-map.csv")

    findings = []
    dms = []  # (dmc, tech name, info name, pilot)

    for info, ilc in GENERAL:
        dms.append((dmc("00-00-00", "00", info, ilc), "Hydraulic power unit", INFO_NAMES[info], "Y"))

    for m in mapping:
        pn = m["PART NUMBER"]
        if pn not in bom:
            findings.append(f"Map row `{pn}` is not in the BOM.")
            continue
        if m["SNS"] not in sns_titles:
            findings.append(f"`{pn}` points to SNS `{m['SNS']}`, which the SNS doesn't define.")
            continue
        name = sns_titles[m["SNS"]] if m["DISASSY"] == "00" else tech_name(bom[pn]["DESCRIPTION"])
        infos = m["EXTRA TASKS"].split()
        if m["LRU"] == "Y":
            infos = ["520", "720"] + infos
        if not infos:
            findings.append(f"`{pn}` is mapped but plans no data module.")
        for info in infos:
            if info not in INFO_NAMES:
                findings.append(f"`{pn}`: information code `{info}` is not in this project's list.")
                continue
            dms.append((dmc(m["SNS"], m["DISASSY"], info, m["ITEM LOCATION"]), name,
                        INFO_NAMES[info], m["PILOT"]))

    codes = [d[0] for d in dms]
    for c in sorted({c for c in codes if codes.count(c) > 1}):
        findings.append(f"Duplicate DMC `{c}`.")

    mapped = {m["PART NUMBER"] for m in mapping}
    undecided = [
        r for pn, r in bom.items()
        if r["MAKE/BUY"] == "Buy" and pn not in mapped and not pn.startswith("ISO ")
    ]

    out = ROOT / "dml"
    out.mkdir(exist_ok=True)

    lines = [
        "# VH-15 data management list",
        "",
        "Generated by `tools/make_dml.py` from the BOM and `sns/bom-sns-map.csv`. Don't edit by hand.",
        "",
        f"{len(dms)} data modules planned; {sum(d[3] == 'Y' for d in dms)} in the pilot.",
        "",
        "| DMC | Technical name | Information name | Pilot |",
        "|---|---|---|---|",
    ]
    lines += [f"| `{c}` | {t} | {i} | {'Yes' if p == 'Y' else ''} |" for c, t, i, p in dms]
    (out / "VH15-DML.md").write_text("\n".join(lines) + "\n", encoding="utf-8")

    cov = ["# VH-15 coverage report", "", "Generated by `tools/make_dml.py`. Don't edit by hand.", ""]
    cov += ["## Map consistency", ""]
    cov += [f"- {f}" for f in findings] or ["No problems found."]
    cov += ["", "## Bought parts with no maintenance decision", ""]
    if undecided:
        cov += [
            "These parts are bought in, so they may need replacing in service, but the map doesn't",
            "say whether they are LRUs. Decide each one, then rerun.",
            "",
            "| BOM item | Part number | Description |",
            "|---|---|---|",
        ]
        cov += [f"| {r['ITEM NO.']} | `{r['PART NUMBER']}` | {r['DESCRIPTION']} |" for r in undecided]
    else:
        cov += ["None."]
    (out / "coverage.md").write_text("\n".join(cov) + "\n", encoding="utf-8")

    print(f"{len(dms)} data modules, {len(findings)} map problems, {len(undecided)} undecided parts")
    return 1 if findings else 0


if __name__ == "__main__":
    sys.exit(main())
